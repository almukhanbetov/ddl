-- Delivery outside Almaty now has a fixed price, shown in the card's title:
-- the card loses its "priced by address" text and the zones/tariffs block goes.
UPDATE site_content
SET data = jsonb_set(
  jsonb_set(
  data,
  '{ru,deliveryPage}',
  ((data #> '{ru,deliveryPage}') - 'zonesTitle' - 'zonesNote' - 'zones') || $${
  "outsideTitle": "Доставка за пределы Алматы — 30 000 ₸",
  "outsideDesc": ""
}$$::jsonb
),
  '{kk,deliveryPage}',
  ((data #> '{kk,deliveryPage}') - 'zonesTitle' - 'zonesNote' - 'zones') || $${
  "outsideTitle": "Алматы қаласынан тыс жерге жеткізу — 30 000 ₸",
  "outsideDesc": ""
}$$::jsonb
),
    updated_at = now()
WHERE id = 1;

